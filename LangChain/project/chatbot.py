import streamlit as st
from langchain.chat_models import init_chat_model
#we can chat init too but there is this other method too
from langchain_mistralai import ChatMistralAI
from dotenv import load_dotenv
from langchain_core.messages import HumanMessage, AIMessage,SystemMessage
load_dotenv()


model=init_chat_model(
    "mistral-small-2506", #it is free model
    temperature=1, #tells creativeness of model
    max_tokens=50
)

#abhi bas aise hi list mai store krke vapas dena mai kafi issues hai. Limit bahut jaldi reach ho jaegi as each time we are providing old content(which might have been already been passed) and new content too each time.

#Abhi AI ko oata  nhi hai ki kya maine bola hai and kya saamne se user ne poocha hai

#For that we have a package in langchain known as messages

#now it defines three types of messages 
# 1. System messages-> These define the tone/nature of the ai system.Like act as a expert, begineer, friendly, harsh nature etc.
# 2. Human messages->these are the messages given by the human
# 3. AI Messages-> these are the response generated by the ai model
#messages=[] #to store history to improve context

messages=[
    SystemMessage(content="You are a funny AI agent.")
] 

print("type 0 to exit")
print("Eter your query below")
#to keep on getting input from user we can use an infinte loop
while True:
    prompt=input("You: ")
    messages.append(HumanMessage(content=prompt))
    if prompt=="0":
        print("Exiting...")
        break
    response = model.invoke(messages) #ab ye seedhe list lega which has old chats and responses too
    messages.append(AIMessage(content=response.content))
    print(f"Bot : {response.content}")

print(messages)
